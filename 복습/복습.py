# 위의 코드를 실행하면 이러한 결과가 나온다.


def R2(x, y, w, b):
    못맞힌것 = np.sum((y - 예측(x, w, b)) ** 2)  # 직선이 못 맞힌 만큼
    평균으로찍기 = np.sum((y - y.mean()) ** 2)  # 그냥 평균으로 답했을 때 틀린 만큼
    return 1 - 못맞힌것 / 평균으로찍기


# 검증은 이걸로 하는데
# R**2은 결정계수이다.
# 평균으로 찍기라는 것은 그냥 모든 예측을 평균으로 잡고하는 아주 게으른 방법이다.
# 이 게으른 방법과 경사하강법으로 구한 식을 비교하여
# 이 게으른 방법보다 내가 얼마나 잘맞히는지를 판단하는 근거가 된다.

# 여기서 결정계수는 0.7989로 대략 80%가량 나오는데
