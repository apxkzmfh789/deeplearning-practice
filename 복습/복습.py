# 여기부터 넘파이와 판다스로 경사하강법을 직접 구현한다.

# 먼저 w * x + b로 아주 간단한 선형모델을 만든다고 가정한다.

# 하나의 식을 먼저 설계했다면 가장 최적으로 예측이 되는 w와 b를 각각 찾아야 한다.
# 이때 x는 설비의 공기온도이고 출력되는 결과값은 공정온도이다.

# 사실상의 x는 입력값이 고정되어 있기 때문에 최적의 w와 b를 찾아서 공정온도와 비교하면 된다.
# 이때 내가 기존의 정답(실제 공정온도)과의 차이를 제곱해서 전부 더한 값이
# SSE이다.

# 즉, 이 SSE(손실)이 클수록 예측이 틀렸기 때문에 차이가 벌어지는데
# SSE가 적어지는 방향으로 w와 b값을 조정해야 한다.

# 하지만 이렇게 SSE를 구하면 문제가 하나 생긴다.
# 바로 데이터가 많을 수록 SSE값이 무한히 커진다는 단점이 있는데
# 이를 데이터의 개수만큼 나눠서 데이터 한 개당 오차를 비교하는 것으로 해결했다.
# SSE를 데이터의 개수만큼 나눈 것이 MSE이다.


def 손실(x, y, w, b):
    틀린정도 = y - 예측(x, w, b)  # 설비마다 (실제 − 예측). 200개
    return np.mean(틀린정도**2)  # 제곱해서 평균. ** 2 = 제곱


h = 0.0001  # 아주 살짝만 밟는다 (크게 밟으면 지금 자리가 아닌 엉뚱한 곳을 재게 됨)


def 기울기_밟아보기(x, y, w, b):
    gw = (손실(x, y, w + h, b) - 손실(x, y, w - h, b)) / (
        2 * h
    )  # w 만 ±h 밀어 본 기울기 (w 의 편미분)
    gb = (손실(x, y, w, b + h) - 손실(x, y, w, b - h)) / (
        2 * h
    )  # b 만 ±h 밀어 본 기울기 (b 의 편미분)
    return gw, gb  # 둘을 묶어 돌려줌 = 그래디언트


# 지금 위의 기울기 밟아보기 함수는 현재 w와 b의 현재 위치의 기울기를 구하는 것이다.
# 현재 손실함수는 2차 함수인데 이는 제곱의 합을 구한 것이기 때문에
# 2차함수 형태로 나오게 되고, 가장 손실이 작은 점을 찾기 위해
# 나아가야 하는 것이다.

# 그렇다면 w와 b의 최적의 값을 구해야 하는데, 그 전에 먼저 기울기부터 구해야한다.
# 왜 기울기부터 구해야 할까?
# 기울기를 구하는 이유는 기울기에는 크게 2가지의 정보가 있다.
# 크기와 방향이다.
# 기울기의 크기가 클수록 경사가 급한(최소가 되는 지점보다 멀리 있음을 의미) 것을 나타내고
# 기울기의 부호가 w를 크게 해야 하는지, 작게 해야 하는 지를 알려준다.
# 만약 기울기의 부호가 음수라면 U자형 포물선이기 때문에 극솟값으로 내려가는 중을 의미한다.
# 따라서 w를 더 크게 해야하고, 기울기의 미분값이 양수라면 극솟값을 지나쳐 올라가는 것을
# 의미하기 때문에 w를 작게 해야 한다.

# 그렇다면 w를 어떻게 최적의 위치로 가게 할 수 있을까?

# 바로 학습률을 이용하는 방법이 있다.
# lr = 0.00001을 이용하여
# 원래  w = w - lr * gw
#       b = b - lr * gb

# 여기서 의문이 생길 것이다.
# w에 왜 기울기와 학습률을 곱한 것을 빼는가?
# 바로 앞에서 얘기했듯이 w가 음수라면 w를 키워야 극솟값에 도달한다.
# 그럼 원래의 w에 기울기와 학습률을 곱한 것을 뺀다면 양수라면 w가 줄어들고
# 음수라면 w가 늘어나게 되는 원리이다.

# 또한 경사하강을 진행하기 전, 표준화를 통한 스케일링을 진행하게 되는데
# 왜 꼭 스케일링을 해줘야 하는 걸까?
# 바로 서로의 단위가 다르기 때문이다.
# 입력 x의 스케일이 크면 w와 b가 손실에 미치는 영향력 차이가 커져서
# 경사하강이 불안정해지기 때문에, 표준화로 이 스케일 차이를 없애
# 안정적으로 수렴하게 만든다.


# =====================================================================
def 학습(z, y, lr=0.1, epochs=300, 보여주기=True):
    w, b = 0.0, 0.0  # 아무 데서나 출발해도 됩니다 (여기선 0)
    for epoch in range(epochs):  # 한 바퀴 = 한 걸음
        gw, gb = 기울기_밟아보기(z, y, w, b)  # ① 어느 쪽이 내리막?
        w = w - lr * gw  # ② 그쪽으로 한 걸음
        b = b - lr * gb
        if 보여주기 and epoch in (0, 1, 2, 5, 10, 30, 100, 299):
            print(
                f"    epoch {epoch:3d}  w={w:7.3f}  b={b:8.3f}  손실 {손실(z, y, w, b):10.4f}"
            )  # 자릿수 지정은 00 미리보기 ①
    return w, b


# 이제 최종적으로 경사하강의 함수가 완성되었다.
# w와 b를 모두 0에서 시작해서
# gw, gb를 각각에 편미분하여 기울기를 구한다.
# 그 기울기와 학습률을 w와 b에 더하여 w와 b를 새로 구한다.
# 이걸 epochs만큼 반복하여 최솟값에 도달하게끔한다.

# 하지만 이때 학습률의 크기가 중요한데
# 0.001, 0.01, 0.1, 1.05 이렇게 놓고 가정해보자

# 0.001은 너무 느리게 가서 최솟값에 도달하는 시간이 너무 오래걸리고
# 0.01도 조금 느리다
# 0.1로 하면 금방 바닥에 도착하는데
# 그럼 1.05 같은 큰 수를 넣으면 어떻게 될까?
# 바로 발산한다.
# 손실이 작아지는 방향으로 w를 갱신해야 하지만,
# 학습률이 너무 크다면 이 손실률이 커져 최솟값에 도달하는 것이 아닌
# 위로 솟구쳐오르는 발산을 하게 된다.


